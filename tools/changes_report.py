def side_by_side(body):
    old = [l[1:] for l in body if l[:1] in ' -']
    new = [l[1:] for l in body if l[:1] in ' +']
    rows = []
    sm = difflib.SequenceMatcher(None, old, new, autojunk=False)
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op == 'equal':
            rows += [(old[i], new[j1 + k], '', '') for k, i in enumerate(range(i1, i2))]
        else:
            a, b = old[i1:i2], new[j1:j2]
            for k in range(max(len(a), len(b))):
                rows.append((a[k] if k < len(a) else '', b[k] if k < len(b) else '',
                             'del' if k < len(a) else '', 'add' if k < len(b) else ''))
    return ''.join(f'<tr><td class="{c1}">{html.escape(x)}</td><td class="{c2}">{html.escape(y)}</td></tr>' for x, y, c1, c2 in rows)

def build_html(recs, path):
    parts = ['<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">',
             '<title>Flagged replay changes</title><style>' + CSS + '</style></head><body><main>',
             '<h1>Records #11 → #18: every hunk, side by side</h1>',
             '<p>Left: previous snapshot, right: this snapshot (training script = log-embedded sources; other files = pristine trees). '
             'Each hunk carries its ledger id, category, switch(es) and provenance. Generated by <code>tools/changes_report.py</code>.</p>',
             '<div class="filter"><label>Filter by switch or category: <input id="q" placeholder="e.g. value_embeds or model-mechanism"></label></div>',
             '<nav>' + ''.join(f'<a href="#r{r["record"]}">r{r["record"]}</a>' for r in recs) + '</nav>']
    for r in recs:
        parts.append(f'<h2 id="r{r["record"]}">r{r["record"]} — {html.escape(str(r.get("title", "")))} '
                     f'<small>({html.escape(r["snapshot_from"])} → {html.escape(r["snapshot_to"])}, {len(r["hunks"])} hunks)</small></h2>')
        for e in r['hunks']:
            fl = ' '.join(f'<span class="tag">{html.escape(str(f))}</span>' for f in as_list(e['flag']))
            cats = ' '.join(f'<span class="tag">{html.escape(c)}</span>' for c in as_list(e['category']))
            key = ' '.join(str(x) for x in as_list(e['flag']) + as_list(e['category']))
            parts.append(f'<div class="hunk" data-k="{html.escape(key)}"><div class="hd"><span class="id">r{r["record"]}/{e["id"]}</span>'
                         f'<span class="tag">{html.escape(e["file"])} {html.escape(e["header"])}</span>{cats}{fl}'
                         f'<span class="tag">provenance: {e["provenance"]}</span><span class="tag">numerics: {e["numerics"]}</span>'
                         f'<span class="desc">{html.escape(str(e["description"]))}</span></div>'
                         f'<div class="sbs"><table>{side_by_side(e["_body"])}</table></div></div>')
    parts.append("""<script>
const q=document.getElementById('q');q.addEventListener('input',()=>{const v=q.value.trim().toLowerCase();
document.querySelectorAll('.hunk').forEach(h=>{h.style.display=!v||h.dataset.k.toLowerCase().includes(v)?'':'none';});});
</script></main></body></html>""")
    open(path, 'w').write('\n'.join(parts))

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--out', default=os.path.join(HERE, 'reports'))
    a = ap.parse_args()
    build(load(), a.out)
    print(f'wrote {a.out}/changes.md and {a.out}/changes.html')

if __name__ == '__main__':
    main()
