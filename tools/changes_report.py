"""Build reports/changes.md and reports/changes.html from ledger/rNN.yaml + diffs/ (pure Python).

changes.md   flag x record matrix (introduced at, lines touched, categories, bundled, provenance), per-record
             summaries, coupled hyperparameters, bundles that remain unbundleable.
changes.html self-contained page: for every record, every hunk side by side (difflib alignment inside the hunk),
             labelled with its ledger id, category, flag(s), provenance and description.
Usage: python -I tools/changes_report.py [--out reports]
"""
import argparse, difflib, glob, html, os, re, sys
from collections import OrderedDict, defaultdict
import yaml
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from diffparse import hunks as parse_hunks

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def as_list(x):
    return x if isinstance(x, list) else [x]

def load():
    recs = []
    for p in sorted(glob.glob(os.path.join(HERE, 'ledger', 'r*.yaml')), key=lambda p: int(re.findall(r'\d+', os.path.basename(p))[0])):
        led = yaml.safe_load(open(p))
        hs = parse_hunks(open(os.path.join(HERE, led['diff'])).read())
        by_key = {(h['file'], h['header']): h for h in hs}
        for e in led['hunks']:
            h = by_key[(e['file'], e['header'])]
            e['_body'] = h['body']
            e['_changed'] = sum(1 for l in h['body'] if l[:1] in '+-')
        recs.append(led)
    return recs

def trainer_flags():
    import ast
    tree = ast.parse(open(os.path.join(HERE, 'train_flagged.py')).read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id == 'FLAGS':
            return list(ast.literal_eval(node.value))
    return []

UNBUNDLEABLE = [
    ('value_embeds', 'value residual removal', 'At #14 the value embedding replaces the layer-0 value residual in the same mixing formula; no record has both, none is built.'),
    ('ve_split', 'init draw order', 'Splitting the table also moves its initialisation after the blocks (the record creates the module there).'),
    ('fp32_small_params', 'scalar vs rotary-table precision', 'Both follow from model.cuda() + bf16 embeddings instead of a global bf16 cast; not separated.'),
    ('code_opts_15', 'its numerics-preserving parts', 'Muon all_gather, pinned loader, persistent window tensor, uncompiled flex call, fetch order: one switch (all argued numerics-identical).'),
    ('code_opts_16', 'its numerics-preserving parts', 'DDP bucket views/no buffer broadcast, set_stance, unbuffered reads, enable_gqa, skipping /1: one switch.'),
    ('code_opts_18', 'rewrite implementation details', 'Grouped Adam, step-start fetch, no no_sync, per-step window copy, no autotuning, Newton-Schulz order, dummy backward: one switch (two parts ulp-level).'),
    ('flex_kernel', 'every later attention mechanism', 'long_context, doc_masking, window_warmup, blockmask_manual, block_window require it (REQUIRES); see the LOO open decision.'),
]

def build(recs, out):
    flags = trainer_flags()
    rec_ids = [r['record'] for r in recs]
    cell = defaultdict(lambda: dict(lines=0, hunks=[], cats=set(), bundled=False, prov=set()))
    coupled = []
    for r in recs:
        for e in r['hunks']:
            for f in as_list(e['flag']):
                c = cell[(f, r['record'])]
                c['lines'] += e['_changed']; c['hunks'].append(e['id'])
                own = [p for p in e.get('parts', []) if str(p.get('flag')) == str(f)]
                # a switch inherits only the categories of its own parts when the hunk is classified per part
                if own:
                    c['cats'] |= {x for p in own for x in as_list(p['category'])}
                else:
                    c['cats'] |= set(as_list(e['category']))
                c['bundled'] |= bool(e['bundled']); c['prov'].add(e['provenance'])
            for cp in e.get('coupled', []):
                coupled.append((r['record'], e['id'], cp))
    keys = [f for f in flags] + sorted({f for (f, _) in cell if str(f).startswith('config:')}) + ['none']
    md = ['# Changes report: records #11 → #18 replayed as flags', '',
          f'Generated by `tools/changes_report.py` from `ledger/r12.yaml` … `ledger/r18.yaml` and `diffs/`. Lines touched = '
          '+/− lines of the hunks that map to the switch (a bundled hunk counts for each of its switches).', '',
          '## Flag × record matrix', '',
          '| switch | introduced at | ' + ' | '.join(f'r{n}' for n in rec_ids) + ' | categories | bundled | provenance |',
          '|---|---|' + '---|' * len(rec_ids) + '---|---|---|']
    for f in keys:
        present = [n for n in rec_ids if (f, n) in cell]
        if not present:
            label = 'arm-muon (not a record diff)' if f == 'optimizer' else 'never in a record diff'
            md.append(f'| `{f}` | {label} | ' + ' | '.join('' for _ in rec_ids) + ' | | | |')
            continue
        cats = sorted(set().union(*[cell[(f, n)]['cats'] for n in present]))
        bund = any(cell[(f, n)]['bundled'] for n in present)
        prov = sorted(set().union(*[cell[(f, n)]['prov'] for n in present]))
        cols = ' | '.join((f"{cell[(f, n)]['lines']} ({len(cell[(f, n)]['hunks'])}h)" if (f, n) in cell else '') for n in rec_ids)
        md.append(f'| `{f}` | r{present[0]} | {cols} | {", ".join(cats)} | {"yes" if bund else "no"} | {", ".join(prov)} |')
    md += ['', '## Per-record summaries', '']
    for r in recs:
        cats = defaultdict(int); fl = OrderedDict()
        for e in r['hunks']:
            for c in as_list(e['category']):
                cats[c] += 1
            for f in as_list(e['flag']):
                if f != 'none':
                    fl[f] = 1
        md.append(f"### r{r['record']} — {r.get('title', '')}")
        md.append(f"{len(r['hunks'])} hunks ({', '.join(f'{k} {v}' for k, v in sorted(cats.items()))}); switches touched: "
                  + ', '.join(f'`{f}`' for f in fl) + f".  Details: `CHANGES/r{r['record']}.md`, `ledger/r{r['record']}.yaml`.")
        md.append('')
    md += ['## Coupled and co-tuned hyperparameters', '', '| record | hunk | note |', '|---|---|---|']
    md += [f'| r{n} | {i} | {c} |' for n, i, c in coupled]
    md += ['', '## Bundles that remain unbundled (and why)', '', '| switch | what stays bundled | why |', '|---|---|---|']
    md += [f'| `{a}` | {b} | {c} |' for a, b, c in UNBUNDLEABLE]
    md += ['', 'Every other bundled hunk was split into separate switches (see the `parts` of bundled hunks in the ledgers).']
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, 'changes.md'), 'w').write('\n'.join(md) + '\n')
    build_html(recs, os.path.join(out, 'changes.html'))

